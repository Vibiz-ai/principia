const SECRET_FILES = { masterKey: 'master.key', passportAdmin: 'passport-admin' } as const

export function secretsDir(env: NodeJS.ProcessEnv): string { return env.PRINCIPIA_SECRETS_DIR || '/secrets' }

/**
 * writes missing secret files (32 random bytes, hex, 0600); returns the names it created. With `passportDir`
 * (PRINCIPIA_PASSPORT_SECRETS_DIR), passport-admin is also copied there: the passport container mounts only that
 * folder, so it never sees master.key.
 */
export function initSecrets(dir: string, opts: { passportDir?: string; owner?: { uid: number; gid: number } | null; passportOwner?: { uid: number; gid: number } | null; only?: string[] } = {}): string[] {
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  const created: string[] = []
  for (const name of Object.values(SECRET_FILES)) {
    if (opts.only && !opts.only.includes(name)) continue
    const p = join(dir, name)
    if (existsSync(p) && readFileSync(p, 'utf8').trim()) continue
    writeFileSync(p, randomBytes(32).toString('hex') + '\n', { mode: 0o600, flag: 'w' })
    chmodSync(p, 0o600)
    created.push(name)
  }
  // CLOUD.md §7.8: only the control plane's user reads these (an install from before agents had their own user
  // has them owned by the node user: they move to the control plane's)
  const files = Object.values(SECRET_FILES).map(n => join(dir, n)).filter(p => existsSync(p))
  if (opts.owner) for (const p of [dir, ...files]) chownSync(p, opts.owner.uid, opts.owner.gid)
  chmodSync(dir, 0o700)
  for (const p of files) chmodSync(p, 0o600)
  if (opts.passportDir) {
    mkdirSync(opts.passportDir, { recursive: true, mode: 0o700 })
    const p = join(opts.passportDir, SECRET_FILES.passportAdmin)
    writeFileSync(p, readFileSync(join(dir, SECRET_FILES.passportAdmin), 'utf8'), { mode: 0o600, flag: 'w' })
    chmodSync(p, 0o600)
    // the passport container runs as its own user: the copy is that user's, never the agents'
    if (opts.passportOwner) for (const q of [opts.passportDir, p]) chownSync(q, opts.passportOwner.uid, opts.passportOwner.gid)
  }
  return created
}

/**
 * The origin your Mac and phone reach (CLOUD.md §12.1). Explicit first, then the one-click hosts' own variables, so a
 * Render or Fly deploy needs no setting at all: PRINCIPIA_PUBLIC_URL, PRINCIPIA_DOMAIN (the caddy profile),
 * RENDER_EXTERNAL_URL, FLY_APP_NAME, RAILWAY_PUBLIC_DOMAIN, else this machine.
 */
export function publicUrlFrom(env: NodeJS.ProcessEnv, port: number): { url: string; source: 'env' | 'domain' | 'render' | 'fly' | 'railway' | 'local' } {
  const clean = (u: string) => u.trim().replace(/\/+$/, '')
  if (env.PRINCIPIA_PUBLIC_URL?.trim()) return { url: clean(env.PRINCIPIA_PUBLIC_URL), source: 'env' }
  if (env.PRINCIPIA_DOMAIN?.trim()) return { url: `https://${clean(env.PRINCIPIA_DOMAIN).replace(/^https?:\/\//, '')}`, source: 'domain' }
  if (env.RENDER_EXTERNAL_URL?.trim()) return { url: clean(env.RENDER_EXTERNAL_URL), source: 'render' }
  if (env.FLY_APP_NAME?.trim()) return { url: `https://${env.FLY_APP_NAME.trim()}.fly.dev`, source: 'fly' }
  if (env.RAILWAY_PUBLIC_DOMAIN?.trim()) return { url: `https://${clean(env.RAILWAY_PUBLIC_DOMAIN).replace(/^https?:\/\//, '')}`, source: 'railway' }
  return { url: `http://127.0.0.1:${port}`, source: 'local' }
}

/** The passport origin ChatGPT and Claude.ai reach: explicit, PASSPORT_DOMAIN, the cloud's own origin when embedded, else local. */
export function passportPublicUrlFrom(env: NodeJS.ProcessEnv, publicUrl: string, embedded: boolean): string {
  const clean = (u: string) => u.trim().replace(/\/+$/, '')
  if (env.OPEN_PASSPORT_PUBLIC_URL?.trim()) return clean(env.OPEN_PASSPORT_PUBLIC_URL)
  if (env.PASSPORT_DOMAIN?.trim()) return `https://${clean(env.PASSPORT_DOMAIN).replace(/^https?:\/\//, '')}`
  if (embedded) return publicUrl
  return 'http://127.0.0.1:8788'
}

/** PRINCIPIA_PASSPORT=embedded: the Open Passport host runs inside this container and is served on the cloud's own origin. */
export const EMBEDDED_PASSPORT_PORT = 8788

function fromFile(dir: string, name: string): string | undefined {
  try { const v = readFileSync(join(dir, name), 'utf8').trim(); return v || undefined } catch { return undefined }
}

export interface LoadedConfig {
  config: ControlConfig; masterKey: Buffer; port: number; host: string; runtime: 'real' | 'fake'; warnings: string[]
  /** where the public URL came from ('local' = this machine only: the connect link needs a tunnel or a setting) */
  publicSource: ReturnType<typeof publicUrlFrom>['source']
  /** PRINCIPIA_PASSPORT=embedded: main starts the host (sources in PRINCIPIA_PASSPORT_SRC) on 127.0.0.1 */
  embeddedPassport: { port: number; dataDir: string; src: string } | null
}

export function loadConfig(env: NodeJS.ProcessEnv, defaults: { consoleDir: string }): LoadedConfig {
  const dir = secretsDir(env)
  const warnings: string[] = []
  const masterKey = parseMasterKey(env.PRINCIPIA_MASTER_KEY || fromFile(dir, SECRET_FILES.masterKey))
  const port = Number(env.PORT || 8787)
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('PORT must be a port number')
  const host = env.HOST || '127.0.0.1'
  const pub = publicUrlFrom(env, port)
  const publicUrl = pub.url
  const embedded = env.PRINCIPIA_PASSPORT === 'embedded'
  let pu: URL
  try { pu = new URL(publicUrl) } catch { throw new Error('PRINCIPIA_PUBLIC_URL must be a URL like https://cloud.example.com') }
  if (pu.protocol !== 'https:' && !['127.0.0.1', 'localhost', '[::1]'].includes(pu.hostname)) warnings.push('PRINCIPIA_PUBLIC_URL is not https: sign-in cookies are not marked Secure. Put the cloud behind HTTPS (a tunnel or a reverse proxy).')
  const adminToken = env.PRINCIPIA_ADMIN_TOKEN || null
  if (adminToken && adminToken.length < 32) throw new Error('PRINCIPIA_ADMIN_TOKEN must have at least 32 characters (or leave it unset and pair with `principia-cloud pair`).')
  const retention = Number(env.PRINCIPIA_LOG_RETENTION_DAYS || 30)
  if (!Number.isFinite(retention) || retention < 1 || retention > 3650) throw new Error('PRINCIPIA_LOG_RETENTION_DAYS must be between 1 and 3650')
  const dataDir = resolve(env.PRINCIPIA_DATA_DIR || './principia-data')
  const internal = embedded ? `http://127.0.0.1:${EMBEDDED_PASSPORT_PORT}` : env.OPEN_PASSPORT_INTERNAL_URL?.replace(/\/+$/, '')
  const passportAdmin = env.OPEN_PASSPORT_ADMIN_TOKEN || fromFile(dir, SECRET_FILES.passportAdmin)
  if (internal && !passportAdmin) warnings.push('OPEN_PASSPORT_INTERNAL_URL is set but no passport admin token was found: companies will move without a passport.')
  const passportPublic = passportPublicUrlFrom(env, publicUrl, embedded)
  return {
    masterKey, port, host, warnings, publicSource: pub.source,
    embeddedPassport: embedded ? { port: EMBEDDED_PASSPORT_PORT, dataDir: join(dataDir, 'passport'), src: resolve(env.PRINCIPIA_PASSPORT_SRC || '/opt/open-passport') } : null,
    runtime: env.PRINCIPIA_RUNTIME === 'fake' ? 'fake' : 'real',
    config: {
      publicUrl,
      adminToken,
      workspaceName: (env.PRINCIPIA_WORKSPACE_NAME || 'Principia Cloud').slice(0, 120),
      consoleDir: resolve(env.PRINCIPIA_CONSOLE_DIR || defaults.consoleDir),
      dataDir,
      workspaceDir: resolve(env.PRINCIPIA_WORKSPACE || './principia-workspace'),
      logRetentionDays: retention,
      connectorAllowPrivate: (env.PRINCIPIA_CONNECTOR_ALLOW_PRIVATE || '').split(',').map(s => s.trim()).filter(Boolean),
      passport: internal && passportAdmin ? { internalUrl: internal, publicUrl: passportPublic, adminToken: passportAdmin } : null,
      passportProxy: embedded && passportAdmin ? internal! : null
    }
  }
}
